import { afterEach, expect, it, vi } from "vitest";
import { MockGymOSApi } from "./MockGymOSApi";
import type { MockDb } from "./store";
import type { PlatformBillingInvoice } from "@/lib/api/GymOSApi";
import { DAY_MS, termEnd } from "../../../convex/subscriptionTerm";
import { termPriceMinor } from "../../../convex/planCatalogue";
afterEach(() => vi.restoreAllMocks());
it.each(["monthly", "annual"] as const)("mock %s quote refresh and activation conserve transfer value", async billingInterval => {
  const now = Date.parse("2026-10-10T12:00:00Z"), end = termEnd(now, billingInterval);
  vi.spyOn(Date, "now").mockReturnValue(now);
  const api = new MockGymOSApi(); api.setBehavior({ latencyMs: 0 }); await api.switchDemoRole("owner");
  const internal = api as unknown as { db: MockDb; platformInvoices: PlatformBillingInvoice[] };
  Object.assign(internal.db.organization, { status: "active", subscriptionPlan: "Basic", billingInterval, currentPeriodEndsAt: new Date(end).toISOString() });
  internal.platformInvoices = [{ id: "funded", gymId: "forge-fitness", gym: "Forge", status: "paid", amount: "", amountMinor: termPriceMinor(49000, billingInterval), date: new Date(now).toISOString(), periodStart: new Date(now).toISOString(), periodEnd: new Date(end).toISOString() }];
  const quote = (await api.requestPlanChange({ plan: "Pro" })).invoice!;
  const payment = { invoiceId: quote.id, method: "cliq" as const, reference: "BANK-1", payerName: "Owner", paidOn: "2026-10-10" };
  vi.mocked(Date.now).mockReturnValue(now + 3 * DAY_MS);
  await expect(api.submitPlatformPayment(payment)).rejects.toMatchObject({ code: "CONFLICT" });
  const refreshed = (await api.requestPlanChange({ plan: "Pro" })).invoice!;
  expect(refreshed.id).not.toBe(quote.id);
  await api.submitPlatformPayment({ ...payment, invoiceId: refreshed.id });
  vi.mocked(Date.now).mockReturnValue(end + DAY_MS);
  const paid = await api.recordPlatformInvoicePayment({ invoiceId: refreshed.id, reference: "BANK-1", reason: "Verified" });
  expect(paid.amountMinor).toBe(refreshed.amountMinor);
  expect(paid.upgradeActivation?.appliedCreditMinor).toBe(0);
  expect(paid.upgradeActivation?.fundedSubscriptionMinor).toBe(refreshed.amountMinor);
  expect(Date.parse(paid.periodStart!)).toBe(end + DAY_MS);
  expect(Date.parse(paid.periodEnd!)).toBeLessThan(termEnd(end + DAY_MS, billingInterval));
});
