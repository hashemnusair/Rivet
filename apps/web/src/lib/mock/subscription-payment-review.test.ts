import { afterEach, expect, it, vi } from "vitest";
import { MockGymOSApi } from "./MockGymOSApi";
import type { MockDb } from "./store";
import type { PlatformBillingInvoice } from "@/lib/api/GymOSApi";
import { DAY_MS, PAYMENT_TERM_DAYS, SUSPENSION_AFTER_DUE_DAYS } from "../../../convex/subscriptionTerm";
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks(); });
it("mock routes submitted renewals to review and retains enforcement clocks on retries/returns", async () => {
  const now = Date.parse("2026-10-10T12:00:00Z");
  vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(now);
  const api = new MockGymOSApi(); api.setBehavior({ latencyMs: 0 });
  await api.switchDemoRole("owner");
  const internal = api as unknown as { db: MockDb; platformInvoices: PlatformBillingInvoice[] };
  internal.platformInvoices = [];
  internal.db.organization.status = "active";
  internal.db.organization.trialEndsAt = undefined;
  internal.db.organization.currentPeriodEndsAt = new Date(now).toISOString();
  await api.reconcilePlatformSubscriptions(now);
  const invoice = internal.platformInvoices[0]!;
  const payment = { invoiceId: invoice.id, method: "cliq" as const, reference: "BANK-1", payerName: "Owner", paidOn: "2026-10-10" };
  await api.submitPlatformPayment(payment);
  const dueAt = invoice.dueAt;
  const firstSubmission = invoice.paymentClaim!.submittedAt;
  vi.setSystemTime(now + 40 * DAY_MS);
  await api.submitPlatformPayment(payment);
  expect(invoice.paymentClaim!.submittedAt).toBe(firstSubmission);
  const threshold = now + (PAYMENT_TERM_DAYS + SUSPENSION_AFTER_DUE_DAYS) * DAY_MS;
  expect((await api.reconcilePlatformSubscriptions(threshold)).suspended).toBe(0);
  expect((await api.reconcilePlatformSubscriptions(threshold + DAY_MS)).suspended).toBe(0);
  expect((await api.getPlatformSnapshot()).auditEvents.filter(event => event.action === "subscription.payment_review_required")).toHaveLength(1);
  await api.rejectPlatformInvoicePayment({ invoiceId: invoice.id, reason: "No transfer" });
  expect((await api.reconcilePlatformSubscriptions(threshold)).suspended).toBe(1);
  expect(invoice.dueAt).toBe(dueAt);
});
