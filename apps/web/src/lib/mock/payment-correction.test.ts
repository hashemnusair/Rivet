import { afterEach, expect, it, vi } from "vitest";
import { MockGymOSApi } from "./MockGymOSApi";
import type { MockDb } from "./store";
import type { PlatformBillingInvoice } from "@/lib/api/GymOSApi";
afterEach(() => vi.useRealTimers());
it.each(["initial", "renewal", "suspended", "upgrade"])("mock %s correction follows the operator return and confirmation contract", async kind => {
  vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date("2026-10-10T12:00:00Z"));
  const api = new MockGymOSApi(); api.setBehavior({ latencyMs: 0 }); await api.switchDemoRole("owner");
  const internal = api as unknown as { db: MockDb; platformInvoices: PlatformBillingInvoice[] };
  internal.db.organization.status = kind === "initial" ? "pending_payment" : kind === "suspended" ? "suspended" : "active";
  internal.db.organization.subscriptionPlan = "Basic";
  internal.platformInvoices = [];
  let invoiceId = "correction";
  if (kind === "upgrade") invoiceId = (await api.requestPlanChange({ plan: "Pro" })).invoice!.id;
  else internal.platformInvoices.push({ id: invoiceId, gymId: "forge-fitness", gym: "Forge", status: "open", firstPayment: kind === "initial", amount: "JOD 49.000", amountMinor: 49000, date: "2026-10-10", dueAt: "2026-10-01T00:00:00Z" });
  const payment = { invoiceId, method: "cliq" as const, reference: "WRONG-1", payerName: "Owner", paidOn: "2026-10-10" };
  const sent = await api.submitPlatformPayment(payment);
  const original = structuredClone(sent.invoice!);
  const requested = await api.requestPaymentCorrection({ invoiceId, reason: "Please return this reference" });
  expect(requested.invoice!.paymentClaim).toEqual(original.paymentClaim);
  expect(requested.invoice!.dueAt).toBe(original.dueAt);
  expect(await api.requestPaymentCorrection({ invoiceId, reason: "Retry" })).toEqual(requested);
  expect((await api.submitPlatformPayment(payment)).invoice).toEqual(requested.invoice);
  await expect(api.submitPlatformPayment({ ...payment, reference: "CORRECT-2" })).rejects.toMatchObject({ code: "CONFLICT" });
  expect((await api.getBillingCheckout()).invoice).toEqual(requested.invoice);
  await api.rejectPlatformInvoicePayment({ invoiceId, reason: "Returned for correction" });
  const corrected = await api.submitPlatformPayment({ ...payment, reference: "CORRECT-2" });
  expect(corrected.invoice!.paymentClaim!.submissionId).not.toBe(original.paymentClaim!.submissionId);
  expect(corrected.invoice!.paymentClaim).toMatchObject({ reference: "CORRECT-2", amountMinor: original.amountMinor });
  expect(corrected.invoice!.dueAt).toBe(original.dueAt);
  await api.requestPaymentCorrection({ invoiceId, reason: "Another correction on the new submission" });
  expect((await api.getPlatformSnapshot()).auditEvents.filter(event => event.action === "invoice.payment_correction_requested")).toHaveLength(2);
  await api.recordPlatformInvoicePayment({ invoiceId, reference: "CORRECT-2", reason: "Matched transfer" });
  expect((await api.getPlatformSnapshot()).invoices.find(row => row.id === invoiceId)).toMatchObject({ status: "paid", paymentClaim: { status: "confirmed", reference: "CORRECT-2" } });
});
