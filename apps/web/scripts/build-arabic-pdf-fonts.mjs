import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const directory = new URL("./pdf-fonts/", import.meta.url);
const regular = readFileSync(new URL("IBMPlexSansArabic-Regular.ttf", directory)).toString("base64");
const bold = readFileSync(new URL("IBMPlexSansArabic-SemiBold.ttf", directory)).toString("base64");
const output = new URL("../convex/pdfArabicFonts.ts", import.meta.url);
writeFileSync(output, `// Generated by scripts/build-arabic-pdf-fonts.mjs. Unmodified IBM Plex Sans Arabic\n// faces under SIL OFL 1.1; license and source checksums: scripts/pdf-fonts/.\n// Bundled bytes keep browser downloads and Convex attachments deterministic.\nexport const ARABIC_PDF_FONTS = {\n  regular: ${JSON.stringify(regular)},\n  bold: ${JSON.stringify(bold)},\n} as const;\n`);
console.log(`Built ${fileURLToPath(output)}`);
